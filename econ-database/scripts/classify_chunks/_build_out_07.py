def main():
    rows = []
    with CHUNK.open(encoding="utf-8") as f:
        for line in f:
            rows.append(json.loads(line))

    out: dict[str, list[str]] = {}
    missing = []
    for row in rows:
        stem = (row.get("stem") or "").strip()
        if not stem:
            continue
        qid = row["id"]
        if qid not in M:
            missing.append(qid)
            continue
        out[qid] = [M[qid]]

    if missing:
        raise SystemExit(f"Missing classifications: {missing}")

    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")

    assigned = len(out)
    nonempty = sum(1 for r in rows if (r.get("stem") or "").strip())
    patterns_used = {p for arr in out.values() for p in arr}
    new_count = sum(1 for p in patterns_used if p not in VOCAB_SET)
    new_patterns = sorted(patterns_used - VOCAB_SET)

    print(f"Nonempty stems in chunk: {nonempty}")
    print(f"Assigned keys: {assigned}")
    print(f"Unique patterns used: {len(patterns_used)}")
    print(f"New (non-vocab) patterns invented: {new_count}")
    for p in new_patterns:
        print(f"  + {p}")


if __name__ == "__main__":
    main()
